<h2>Reklamáció kezelése</h2>
<p>Ha a szülő a fizetési folyamatban hibát észlel, vagy a fizetett összeg és a Digifoodban látható állapot eltér, elsődlegesen az intézmény ügyfélszolgálatával kell felvenni a kapcsolatot. A hibabejelentés során hasznos adat a fizetési referencia, valamint a CIB tranzakciós adatok közül a TRID és az ANUM.</p>

<h2>Visszatérítés</h2>
<p>Az online fizetéshez kapcsolódó visszatérítésről kizárólag az adott intézmény dönthet. A Digifood technikai felületként támogatja a tranzakció azonosítását, de a visszafizetés jogalapját és összegét az intézmény vizsgálja meg.</p>

<h2>Mikor lehet indokolt a visszatérítés?</h2>
<ul>
    <li>tévesen rögzített vagy duplán teljesített befizetés;</li>
    <li>intézményi jóváírás vagy utólagos korrekció;</li>
    <li>jogos reklamáció alapján megállapított eltérés.</li>
</ul>

<h2>Bankkártyás reklamáció</h2>
<p>Ha a kártyabirtokos szerint a probléma a bankkártya terhelésével, jóváhagyásával vagy zárolásával kapcsolatos, a kibocsátó bank ügyfélszolgálata tud elsődleges tájékoztatást adni. A kereskedői oldali adategyeztetéshez az intézmény és a Digifood a CIB tranzakciós mezőket használja.</p>
